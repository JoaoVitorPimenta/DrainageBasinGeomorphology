def calculateMorphometrics(demArray,noData,gt,proj,rows,cols,drainageBasinLayer,streamLayer,demLayer,feedback,precisionSnapCoordinates,minimumChannelLength,nPoints,limitForValleyFloor,minForValleyHeight,useLongestRiver,nSectionsSL,pointsMidline):
    feedback.setProgress(0)
    total = drainageBasinLayer.featureCount()
    step = 100.0 / total if total else 0

    gdfConcatenateds = []
    
    streamsInside = getStreamsInsideLayer(streamLayer, drainageBasinLayer, feedback, precisionSnapCoordinates)
    gdfStream = createGdfStream(streamsInside)
    obtainFirstAndLastPoint(gdfStream)
    createOrderColumn(gdfStream)
    fillOrder(gdfStream)
    mergeStreams(gdfStream)

    for idx, basin in enumerate(drainageBasinLayer.getFeatures()):
        feedback.setProgressText('Basin id '+str(basin.id())+' processing starting...')
        gdfShape = createGdfShape(basin)
        gdfStreamsInside = selectStreamsInsideBasin(gdfStream, gdfShape)
        if feedback.isCanceled():
            return
        calculateStreamLength(gdfStreamsInside,minimumChannelLength)
        gdfLinear = createGdfLinear(gdfStreamsInside)
        calculateStreamNumber(gdfStreamsInside,gdfLinear)
        calculateTotalStreamLength(gdfStreamsInside,gdfLinear)
        calculateMeanStreamLength(gdfStreamsInside,gdfLinear)
        calculateStreamLengthRatio(gdfLinear)
        calculateStreamLengthRatioMean(gdfLinear)
        calculateBifurcationRatio(gdfLinear)
        calculateBifurcationRatioMean(gdfLinear)
        calculateRhoCoefficient(gdfLinear)
        calculateSinuosityIndex(gdfStreamsInside,gdfLinear,useLongestRiver,precisionSnapCoordinates)
        if feedback.isCanceled():
            return
        calculateAreaPerimeter(gdfShape)
        calculateFitnessRatio(gdfShape,gdfLinear,gdfStreamsInside,useLongestRiver,precisionSnapCoordinates)
        calculateBasinLength(gdfStreamsInside,gdfShape,basin,feedback,useLongestRiver,precisionSnapCoordinates)
        calculateWanderingRatio(gdfShape,gdfLinear,gdfStreamsInside,useLongestRiver,precisionSnapCoordinates)
        calculateDrainageDensity(gdfShape,gdfLinear)
        calculateStreamFrequency(gdfShape,gdfLinear)
        calculateDrainageTexture(gdfShape,gdfLinear)
        calculateLengthOverlandFlow(gdfLinear)
        calculateConstantChannel(gdfLinear)
        calculateDrainageIntensity(gdfLinear)
        calculateInfiltrationNumber(gdfLinear)
        calculateCirculatoryRatio(gdfShape)
        calculateElongationRatio(gdfShape)
        calculateFormFactor(gdfShape)
        calculateLemniscateRatio(gdfShape)
        calculateShapeIndex(gdfShape)
        calculateCompactnessCoefficient(gdfShape)
        if feedback.isCanceled():
            return
        gdfRelief = createGdfRelief()
        calculateMinMaxMeanElevation(demArray,noData,gt,proj,rows,cols,basin,gdfRelief,feedback)
        calculateRelief(gdfRelief)
        calculateReliefRatio(gdfRelief,gdfShape)
        calculateRelativeRelief(gdfRelief,gdfShape)
        calculateRuggednessNumber(gdfRelief,gdfLinear)
        calculateDissectionIndex(gdfRelief)
        calculateGradientRatio(gdfStreamsInside,gdfLinear,demLayer,gdfRelief,useLongestRiver,precisionSnapCoordinates)
        if feedback.isCanceled():
            return
        gdfTectonic = createGdfTectonic()
        skelet = calculateVoronoiSkeleton(gdfShape, pointsMidline, min_length=0.0)
        midline = longestPath(skelet)
        TransverseTopographicSymmetryFactor(midline, gdfStreamsInside, gdfShape, gdfTectonic, nPoints, basin, feedback, useLongestRiver,precisionSnapCoordinates)
        assimetryIndex(gdfShape, gdfStreamsInside, gdfTectonic, useLongestRiver,precisionSnapCoordinates)
        calculateSLindexMainChannel(gdfStreamsInside,demLayer,gdfTectonic,useLongestRiver, precisionSnapCoordinates, nSectionsSL)
        valleyFloorWidthHeight(gdfStreamsInside, gdfShape, nPoints, demLayer, gdfTectonic, limitForValleyFloor, minForValleyHeight, feedback, useLongestRiver,precisionSnapCoordinates)
        gdfConcatenated = createGdfConcatenated(gdfLinear,gdfShape,gdfRelief,basin,gdfTectonic)
        gdfConcatenateds.append(gdfConcatenated)

        barProgress = int((idx + 1) * step)
        feedback.setProgress(barProgress)
        feedback.setProgressText('Basin id '+str(basin.id())+' processing completed')

    if feedback.isCanceled():
        return

    gdfMostColumns = max(gdfConcatenateds, key=lambda df: len(df.columns))
    gdfFinal = gpd.pd.concat(gdfConcatenateds, ignore_index=False, axis=0, sort=False)
    gdfFinal = gdfFinal.reindex(columns=gdfMostColumns.columns)

    return gdfFinal

def varimaxRotator(loadings, normalize=True, max_iter=1000, tol=1e-5):
    X = loadings.copy()
    nRows, nCols = X.shape

    if normalize:
        norms = np.sqrt(np.sum(X**2, axis=1, keepdims=True))
        X = X / norms

    R = np.eye(nCols)

    nIter = 0
    d = 0
    for iteration in range(max_iter):
        d_old = d
        Lambda = np.dot(X, R)
        u, s, vh = np.linalg.svd(np.dot(X.T, np.asarray(Lambda)**3 - (1/nRows) * np.dot(Lambda, np.diag(np.diag(np.dot(Lambda.T, Lambda))))))
        R = np.dot(u, vh)
        d = np.sum(s)
        nIter += 1
        if (d - d_old) / d_old < tol:
            break

    rotated = np.dot(X, R)

    if normalize:
        rotated = rotated * norms

    return rotated, nIter

def jenksBreaks(data, n_classes):
    data = np.sort(np.asarray(data, dtype=float))
    n = len(data)
    if n < n_classes:
        raise QgsProcessingException('Insufficient data for Fisher-Jenks classification without any class colapse. Try again with more basins or more parameters.')
    mat1 = np.full((n + 1, n_classes + 1), np.inf)
    mat2 = np.zeros((n + 1, n_classes + 1), dtype=int)
    mat1[0, :] = 0.0

    cumsum = np.zeros(n + 1)
    cumsum_sq = np.zeros(n + 1)

    for i in range(1, n + 1):
        cumsum[i] = cumsum[i - 1] + data[i - 1]
        cumsum_sq[i] = cumsum_sq[i - 1] + data[i - 1] ** 2

    for j in range(1, n_classes + 1):
        for i in range(1, n + 1):
            for m in range(j - 1, i):
                w = i - m
                s1 = cumsum[i] - cumsum[m]
                s2 = cumsum_sq[i] - cumsum_sq[m]
                variance = s2 - (s1 * s1) / w

                val = mat1[m, j - 1] + variance
                if val < mat1[i, j]:
                    mat1[i, j] = val
                    mat2[i, j] = m

    breaks = np.zeros(n_classes + 1)
    breaks[-1] = data[-1]

    idx = n
    for j in range(n_classes, 0, -1):
        idx = mat2[idx, j]
        breaks[j - 1] = data[idx - 1]
    breaks[0] = data[0]

    if len(np.unique(breaks)) != len(breaks):
        bad_value = breaks[np.where(np.diff(breaks) == 0)[0][0]]
        data = data[data != bad_value]
        new_breaks = jenksBreaks(data, n_classes)
        breaks[0] = float('-inf')
        breaks[-1] = float('inf')
        return new_breaks

    breaks[0] = float('-inf')
    breaks[-1] = float('inf')
    return breaks

def calcPCA(drainageBasinLayer,streamLayer,demLayer,feedback,precisionSnapCoordinates,decimalPlaces,selectedParametersDirectly,selectedParametersInversely,useSimpleCpFormula,pathCorrMatrix,pathVarExplained,pathRotUnrot,pathRankCp,basinsRanked,pathParameters,minimumChannelLength,nPoints,limitForValleyFloor,minForValleyHeight,useLongestDrainage,nSectionsSL,pointsMidline):

    demArray, noData, gt, proj, rows, cols = loadDEM(demLayer)

    if selectedParametersDirectly and selectedParametersInversely is None:
        raise QgsProcessingException('No parameters were selected.')
    
    equals = set(selectedParametersDirectly) & set(selectedParametersInversely)

    if equals:
        nameEquals = ", ".join(map(str, equals))
        raise QgsProcessingException(
            'The same parameter cannot be selected for both the directly proportional and inversely proportional parameter lists, the following parameters were selected in both lists: ' + str(nameEquals)
        )

    allSelectedParameters = selectedParametersDirectly + selectedParametersInversely
    if 'None' in allSelectedParameters:
        allSelectedParameters.remove('None')

    gdfMorpParam = calculateMorphometrics(demArray,noData,gt,proj,rows,cols,drainageBasinLayer,streamLayer,demLayer,feedback,precisionSnapCoordinates,minimumChannelLength,nPoints,limitForValleyFloor,minForValleyHeight,useLongestDrainage,nSectionsSL,pointsMidline)
    gdfMorpParam = gdfMorpParam[allSelectedParameters]
    gdfMorpParam.to_csv(pathParameters, index=True, header=True, float_format='%.' + str(decimalPlaces)+ 'f')

    for col in allSelectedParameters:
        basinsWithNan = gdfMorpParam[gdfMorpParam[col].isna()].index.tolist()
        
        for basin in basinsWithNan:
            feedback.pushWarning(str(basin) + ' does not have the morphometric parameter ' + str(col) + ' so the parameter will be ignored in the analysis.')

    gdfWithSelectedParameters = gdfMorpParam.loc[:, allSelectedParameters].dropna(axis=1)    
    X = gdfWithSelectedParameters.values

    selectedParametersDirectly = [col for col in selectedParametersDirectly if col in gdfWithSelectedParameters.columns]
    selectedParametersInversely = [col for col in selectedParametersInversely if col in gdfWithSelectedParameters.columns]

    covMatrix = np.corrcoef(X, rowvar=False)
    paramNames = gdfWithSelectedParameters.columns
    dfCorr = gpd.pd.DataFrame(covMatrix, columns=paramNames, index=paramNames)

    eigVals, eigVecs = np.linalg.eigh(dfCorr)
    idx = eigVals.argsort()[::-1]
    eigVals = eigVals[idx]
    eigVecs = eigVecs[:, idx]

    k = np.sum(eigVals > 1.0)
    loadings = eigVecs[:, :k] * np.sqrt(eigVals[:k])

    if k == 0:
        raise QgsProcessingException('No componentes with eigenvalues greater than 1 were found, the comparative analysis is impossible')

    rotatedLoadings, nIter = varimaxRotator(loadings)
    selectedIndices = []
    for comp in range(rotatedLoadings.shape[1]):
        idx = np.argmax(np.abs(rotatedLoadings[:, comp]))
        selectedIndices.append(idx)

    selectedIndices = list(dict.fromkeys(selectedIndices))

    selectedParams = paramNames[selectedIndices]

    nVars = dfCorr.shape[0]

    initSs = eigVals
    initPct = eigVals / nVars * 100
    initCum = np.cumsum(initPct)

    extrSs = np.sum(loadings ** 2, axis=0)
    extrPct = extrSs / nVars * 100
    extrCum = np.cumsum(extrPct)

    rotSs = np.sum(rotatedLoadings ** 2, axis=0)
    rotPct = rotSs / nVars * 100
    rotCum = np.cumsum(rotPct)

    nVarsLen = len(initSs)
    kLen = len(extrSs)

    extrSsFull = np.full(nVarsLen, np.nan)
    extrPctFull = np.full(nVarsLen, np.nan)
    extrCumFull = np.full(nVarsLen, np.nan)

    rotSsFull = np.full(nVarsLen, np.nan)
    rotPctFull = np.full(nVarsLen, np.nan)
    rotCumFull = np.full(nVarsLen, np.nan)

    extrSsFull[:kLen] = extrSs
    extrPctFull[:kLen] = extrPct
    extrCumFull[:kLen] = extrCum

    rotSsFull[:kLen] = rotSs
    rotPctFull[:kLen] = rotPct
    rotCumFull[:kLen] = rotCum

    corrSelected = dfCorr.loc[selectedParams, selectedParams]
    colSums = corrSelected.sum(axis=0)
    totalSum = corrSelected.values.sum()

    weights = colSums / totalSum

    rankingDirect = gdfWithSelectedParameters.loc[:, list(set(selectedParams) & set(selectedParametersDirectly))] \
        .rank(method='min', ascending=False)

    rankingInverse = gdfWithSelectedParameters.loc[:, list(set(selectedParams) & set(selectedParametersInversely))] \
        .rank(method='min', ascending=True)

    rankingPerParam = gpd.pd.concat([rankingDirect, rankingInverse], axis=1)

    if useSimpleCpFormula is True:
        vulnerabilityIndex = rankingPerParam.sum(axis=1) / rankingPerParam.shape[1]
    else:
        weightedRanking = rankingPerParam * weights
        vulnerabilityIndex = weightedRanking.sum(axis=1)

    ranking = vulnerabilityIndex.rank(method='min', ascending=True)
    nClasses = 5

    breaks = jenksBreaks(vulnerabilityIndex, nClasses)

    priorityJenks = np.digitize(vulnerabilityIndex.values, breaks[1:-1], right=True) +1

    priorityLabels = {
        5: "Very low",
        4: "Low",
        3: "Medium",
        2: "High",
        1: "Very high"
    }

    priorityText = np.vectorize(priorityLabels.get)(priorityJenks)

    dfCorr.to_csv(pathCorrMatrix, index=True, float_format='%.' + str(decimalPlaces)+ 'f')

    dfVariance = gpd.pd.DataFrame({
        "Total_Initial": initSs,
        "%_Variance_Initial": initPct,
        "%_Cumulative_Initial": initCum,
        "Total_Extracted": extrSsFull,
        "%_Variance_Extracted": extrPctFull,
        "%_Cumulative_Extracted": extrCumFull,
        "Total_Rotated": rotSsFull,
        "%_Variance_Rotated": rotPctFull,
        "%_Cumulative_Rotated": rotCumFull
    })

    dfVariance.to_csv(pathVarExplained, index_label="Component", float_format='%.' + str(decimalPlaces)+ 'f')


    dfLoadingsCombined = gpd.pd.DataFrame(index=paramNames)

    for i in range(k):
        dfLoadingsCombined[f"{i+1} Unrot"] = loadings[:, i]

    for i in range(k):
        dfLoadingsCombined[f"{i+1} Rot"] = rotatedLoadings[:, i]

    dfLoadingsCombined[f"Rotation converged in {nIter} iterations."] = "" 

    dfLoadingsCombined.to_csv(pathRotUnrot, index=True, float_format='%.' + str(decimalPlaces)+ 'f')

    if useSimpleCpFormula is True:
        rankingPerParam["Compound parameter"] = vulnerabilityIndex
    else:
        rankingPerParam["Compound parameter weighted"] = vulnerabilityIndex
    rankingPerParam["Ranking"] = ranking
    rankingPerParam["Priority"] = priorityText
    if useSimpleCpFormula is False:
        weightedRankingCols = weightedRanking.add_suffix(" weighted")
        rankingPerParam = gpd.pd.concat(
            [weightedRankingCols, 
             rankingPerParam["Compound parameter weighted"],
             rankingPerParam["Ranking"],
             rankingPerParam["Priority"]],
            axis=1
        )

    rankingPerParam.to_csv(pathRankCp, index=True, float_format='%.' + str(decimalPlaces)+ 'f')

    for i, feat in enumerate(drainageBasinLayer.getFeatures()):
        f = QgsFeature()
        f.setGeometry(feat.geometry())
        attrs = feat.attributes()
        attrs.append(float(ranking.iloc[i]))
        attrs.append(str(priorityText[i]))
        f.setAttributes(attrs)

        basinsRanked.addFeature(f)