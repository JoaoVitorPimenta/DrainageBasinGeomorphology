def TransverseTopographicSymmetryFactor(midline, gdfStreamsInside, gdfShape, nPoints, basin, feedback, useLongestRiver, precisionSnapCoordinates=0.001):
    maxOrder = gdfStreamsInside['order'].max()
    filterMaxOrder = gdfStreamsInside[gdfStreamsInside['order'] == maxOrder]

    if useLongestRiver is True:

        lines = []

        for geom in gdfStreamsInside.geometry:

            if geom is None or geom.is_empty:
                continue

            if geom.geom_type == "LineString":
                lines.append(geom)

            elif geom.geom_type == "MultiLineString":
                lines.extend(list(geom.geoms))



        merged = MultiLineString(lines)
        filterMaxOrder = gdfStreamsInside[gdfStreamsInside['order'] == maxOrder]
        mainRiver = longestDrainage(
            merged,
            tuple(filterMaxOrder.iloc[-1]['last']),
            precisionSnapCoordinates
        )
        
        filterMaxOrder = gpd.GeoDataFrame(geometry=[mainRiver])

    lines = []

    for geom in gdfStreamsInside.geometry:

        if geom.geom_type == "LineString":
            lines.append(geom)

        elif geom.geom_type == "MultiLineString":
            lines.extend(list(geom.geoms))

    mainRiver = filterMaxOrder.geometry.iloc[0]

    boundary = gdfShape.geometry.unary_union.boundary


    fractions = np.linspace(
        0.1,
        0.9,
        nPoints
    )


    points = [
        midline.interpolate(
            fraction,
            normalized=True
        )
        for fraction in fractions
    ]


    distanceLinesDa = []
    distanceLinesDd = []
    ttsValues = []
    noRiverPoints = 0


    for i, point in enumerate(points):

        eps = 0.001


        p1 = midline.interpolate(
            max(
                0,
                midline.project(point) - eps
            )
        )


        p2 = midline.interpolate(
            min(
                midline.length,
                midline.project(point) + eps
            )
        )


        dx = p2.x - p1.x
        dy = p2.y - p1.y


        nx = -dy
        ny = dx


        norm = np.sqrt(nx**2 + ny**2)


        if norm == 0:
            continue


        nx /= norm
        ny /= norm


        length = midline.length * 2


        linePositive = LineString([
            point,
            (
                point.x + nx * length,
                point.y + ny * length
            )
        ])


        lineNegative = LineString([
            point,
            (
                point.x - nx * length,
                point.y - ny * length
            )
        ])

        boundaryPositive = linePositive.intersection(
            boundary
        )

        boundaryNegative = lineNegative.intersection(
            boundary
        )


        def getNearestPoint(intersection, origin):

            if intersection.is_empty:
                return None

            if intersection.geom_type == "Point":

                return intersection

            elif intersection.geom_type == "MultiPoint":

                return min(
                    intersection.geoms,
                    key=lambda geom: origin.distance(geom)
                )

            elif intersection.geom_type == "GeometryCollection":

                points = [
                    geom
                    for geom in intersection.geoms
                    if geom.geom_type == "Point"
                ]

                if not points:
                    return None

                return min(
                    points,
                    key=lambda geom: origin.distance(geom)
                )

            return None

        boundaryPointPositive = getNearestPoint(
            boundaryPositive,
            point
        )

        boundaryPointNegative = getNearestPoint(
            boundaryNegative,
            point
        )

        validPositive = None
        validNegative = None


        if boundaryPointPositive is not None:

            validPositive = LineString([
                point,
                boundaryPointPositive
            ])


        if boundaryPointNegative is not None:

            validNegative = LineString([
                point,
                boundaryPointNegative
            ])

        riverPositive = None
        riverNegative = None


        if validPositive is not None:

            riverPositive = validPositive.intersection(
                mainRiver
            )


        if validNegative is not None:

            riverNegative = validNegative.intersection(
                mainRiver
            )

        riverCandidates = []


        if (
            riverPositive is not None
            and not riverPositive.is_empty
        ):

            riverPointPositive = getNearestPoint(
                riverPositive,
                point
            )

            if riverPointPositive is not None:

                riverCandidates.append({
                    "riverPoint": riverPointPositive,
                    "boundaryPoint": boundaryPointPositive
                })


        if (
            riverNegative is not None
            and not riverNegative.is_empty
        ):

            riverPointNegative = getNearestPoint(
                riverNegative,
                point
            )

            if riverPointNegative is not None:

                riverCandidates.append({
                    "riverPoint": riverPointNegative,
                    "boundaryPoint": boundaryPointNegative
                })

        if not riverCandidates:

            noRiverPoints += 1
            continue

        selected = min(
            riverCandidates,
            key=lambda candidate: point.distance(
                candidate["riverPoint"]
            )
        )


        riverPoint = selected["riverPoint"]

        boundaryPoint = selected["boundaryPoint"]

        midlineRiver = LineString([
            point,
            riverPoint
        ])


        riverBoundary = LineString([
            point,
            boundaryPoint
        ])


        distanceLinesDa.append({
            "id": i + 1,
            "Da": midlineRiver.length,
            "Dd": riverBoundary.length,
            "TTSF": midlineRiver.length /
                    (riverBoundary.length),
            "geometry": midlineRiver
        })


        distanceLinesDd.append({
            "id": i + 1,
            "Da": midlineRiver.length,
            "Dd": riverBoundary.length,
            "TTSF": midlineRiver.length /
                    (riverBoundary.length),
            "geometry": riverBoundary
        })


        ttsValues.append({
            "id": i + 1,
            "distanceA": midlineRiver.length,
            "distanceB": riverBoundary.length,
            "TTSF": midlineRiver.length /
                    (riverBoundary.length)
        })

    if len(ttsValues) == 0:

        feedback.pushWarning(
            f"No points from the midline intersected the main river in basin ID {basin.id()}. "
            f"TTSF calculation could not be performed."
        )

        return None


    if noRiverPoints > 0:

        feedback.pushWarning(
            f"{noRiverPoints} point(s) did not intersect the main river in basin ID {basin.id()} "
            f"during the TTSF calculation."
        )


    gdfDa = gpd.GeoDataFrame(
        distanceLinesDa,
        crs=gdfShape.crs
    )

    gdfDd = gpd.GeoDataFrame(
        distanceLinesDd,
        crs=gdfShape.crs
    )

    meanTTSF = gdfDa["TTSF"].mean()

    gdfDa["TTSF_mean"] = meanTTSF
    gdfDd["TTSF_mean"] = meanTTSF

    return gdfDa, gdfDd


def calculateDaDd(drainageBasinLayer, streamLayer, feedback, precisionSnapCoordinates, minimumChannelLength, nPoints, da, dd, useLongestRiver, nPointsMidline):
    feedback.setProgress(0)
    total = drainageBasinLayer.featureCount()
    step = 100.0 / total if total else 0

    streamsInside = getStreamsInsideLayer(
        streamLayer, drainageBasinLayer,
        feedback, precisionSnapCoordinates
    )

    gdfStream = createGdfStream(streamsInside)
    obtainFirstAndLastPoint(gdfStream)
    createOrderColumn(gdfStream)
    fillOrder(gdfStream)
    mergeStreams(gdfStream)

    Das = []
    Dds = []

    for idx, basin in enumerate(drainageBasinLayer.getFeatures()):
        feedback.setProgressText('Basin id '+str(basin.id())+' processing starting...')
        gdfShape = createGdfShape(basin)
        gdfStreamsInside = selectStreamsInsideBasin(gdfStream, gdfShape)
        calculateStreamLength(gdfStreamsInside,minimumChannelLength)

        skeleton = calculateVoronoiSkeleton(gdfShape, nPointsMidline)
        if skeleton is None:
            continue

        midline = longestPath(skeleton)
        if midline is None:
            continue

        result = TransverseTopographicSymmetryFactor(
            midline,
            gdfStreamsInside,
            gdfShape,
            nPoints,
            basin,
            feedback,
            useLongestRiver,
            precisionSnapCoordinates
        )
        if result is not None:
            gdfDa, gdfDd = result
        gdfDa["basin_id"] = int(basin.id())
        gdfDd["basin_id"] = int(basin.id())
        if feedback.isCanceled():
            return
        barProgress = int((idx + 1) * step)
        feedback.setProgress(barProgress)
        feedback.setProgressText('Basin id '+str(basin.id())+' processing completed')
        Das.append(gdfDa)
        Dds.append(gdfDd)
    gdfFinalDa = gpd.GeoDataFrame(
        gpd.pd.concat(Das, ignore_index=True),
        crs=Das[0].crs
    )
    gdfFinalDd = gpd.GeoDataFrame(
        gpd.pd.concat(Dds, ignore_index=True),
        crs=Dds[0].crs
    )
    for _, row in gdfFinalDa.iterrows():

        feature = QgsFeature()

        feature.setGeometry(
            QgsGeometry.fromWkt(
                row.geometry.wkt
            )
        )

        feature.setAttributes([
            int(row["basin_id"]),
            float(row["Da"]),
            float(row["Dd"]),
            float(row["TTSF"]),
            float(row["TTSF_mean"])
        ])

        da.addFeature(feature)

    for _, row in gdfFinalDd.iterrows():

        feature = QgsFeature()

        feature.setGeometry(
            QgsGeometry.fromWkt(
                row.geometry.wkt
            )
        )

        feature.setAttributes([
            int(row["basin_id"]),
            float(row["Da"]),
            float(row["Dd"]),
            float(row["TTSF"]),
            float(row["TTSF_mean"])
        ])

        dd.addFeature(feature)

    return
